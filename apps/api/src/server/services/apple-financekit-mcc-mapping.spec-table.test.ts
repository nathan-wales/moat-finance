const SPEC_RANGE_RULES = [
	{ from: 3000, to: 3350, category: "Flights" },
	{ from: 3351, to: 3500, category: "Travel" },
	{ from: 3501, to: 3999, category: "Travel" },
	{ from: 4000, to: 4799, category: "Auto & Transport" },
	{ from: 4800, to: 4999, category: "Bills & Utilities" },
	{ from: 5000, to: 5599, category: "Shopping" },
	{ from: 5600, to: 5699, category: "Clothing" },
	{ from: 5700, to: 7299, category: "Shopping" },
	{ from: 7300, to: 7999, category: "Business Services" },
	{ from: 8000, to: 8999, category: "Business Services" },
	{ from: 9000, to: 9999, category: "Taxes" },
];

describe("apple-financekit spec table parity", () => {
	it("implements every exact MCC from the spec", () => {
		for (const [mcc, expectedCategory] of Object.entries(
			SPEC_EXACT_MCC_TO_CATEGORY,
		)) {
			const normalized = mcc.padStart(4, "0");
			assert.equal(
				EXACT_MCC_TO_MOAT_CATEGORY[normalized],
				expectedCategory,
				`MCC ${normalized}`,
			);
			assert.equal(
				categoryFromMerchantCategoryCode(mcc),
				expectedCategory,
				`resolver MCC ${normalized}`,
			);
		}
	});

	it("implements ordered range rules from the spec", () => {
		assert.deepEqual(RANGE_MCC_TO_MOAT_CATEGORY, SPEC_RANGE_RULES);
	});

	it("maps spec example merchants via MCC", () => {
		const examples: Array<[string, string]> = [
			["5812", "Eating Out"],
			["5814", "Eating Out"],
			["5200", "Home"],
			["5411", "Groceries"],
			["5541", "Gas"],
			["3001", "Flights"],
			["7011", "Travel"],
			["5815", "Subscriptions"],
			["6513", "Mortgage & Rent"],
			["8220", "Education"],
			["5995", "Pets"],
			["7311", "Business Services"],
			["6011", "Fees"],
		];

		for (const [mcc, expected] of examples) {
			assert.equal(categoryFromMerchantCategoryCode(mcc), expected, mcc);
		}
	});

	it("satisfies acceptance criteria category resolution", () => {
		const acceptance: Array<[string | null, string]> = [
			["5812", "Eating Out"],
			["5411", "Groceries"],
			["5541", "Gas"],
			["5200", "Home"],
			["7011", "Travel"],
			["3001", "Flights"],
			["6513", "Mortgage & Rent"],
			["5815", "Subscriptions"],
			["8220", "Education"],
			["0742", "Pets"],
			[null, "Uncategorized"],
		];

		for (const [mcc, expected] of acceptance) {
			assert.equal(categoryFromMerchantCategoryCode(mcc), expected);
		}

		assert.equal(mapAppleFinanceKitCategory("RESTAURANTS"), "Eating Out");
		assert.equal(mapAppleFinanceKitCategory(undefined), "Uncategorized");
		assert.equal(mapAppleFinanceKitCategory(null), "Uncategorized");
	});

	it("does not fall through numeric MCC to legacy enum strings", () => {
		assert.equal(mapAppleFinanceKitCategory("5812"), "Eating Out");
		assert.notEqual(mapAppleFinanceKitCategory("5812"), "Uncategorized");
	});
});
