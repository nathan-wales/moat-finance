#!/usr/bin/env node
// Regenerates scripts/self-host/crontab from the `crons` array in apps/api/vercel.json.
// apps/api/vercel.json is the single source of truth for scheduled jobs: Vercel reads
// it directly for hosted deploys, and the self-hosted `cron` container runs the
// generated crontab.
// Usage (repo root): node scripts/self-host/generate-crontab.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const vercelJson = join(here, "../../apps/api/vercel.json");
const { crons } = JSON.parse(readFileSync(vercelJson, "utf8"));
if (!Array.isArray(crons)) {
	throw new Error("apps/api/vercel.json must have a `crons` array of { path, schedule }");
}
for (const c of crons) {
	if (typeof c?.path !== "string" || !c.path.startsWith("/api/cron/") || typeof c?.schedule !== "string") {
		throw new Error(`Invalid cron entry in apps/api/vercel.json: ${JSON.stringify(c)}`);
	}
}

const lines = [
	"# GENERATED by scripts/self-host/generate-crontab.mjs from apps/api/vercel.json `crons` — do not edit by hand.",
	"# Schedules are UTC. Each job GETs the path on the api service",
	"# with `Authorization: Bearer $CRON_SECRET` via run-cron.sh.",
	"",
	...crons.map((c) => `${c.schedule} /bin/sh /self-host/run-cron.sh ${c.path}`),
	"",
];

writeFileSync(join(here, "crontab"), lines.join("\n"));
console.log(`Wrote ${crons.length} cron entries to scripts/self-host/crontab`);
