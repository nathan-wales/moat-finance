import type { AiReportSummary } from "@moat/contracts";
import { Skeleton } from "@moat/ui";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { FlaskConical } from "lucide-react";
import { useApiClient } from "../api-client-context";
import { useMoatNavigation } from "../navigation-context";
import { AiReportDetailPage } from "./ai-report-detail-page";
import { ReportCard } from "./report-card";
import type { AiReportsPageProps } from "./types";

const DEFAULT_CAPABILITIES = {
	shareViaLink: true,
	updateSnapshot: true,
} as const;

export function AiReportsPage({
	capabilities = DEFAULT_CAPABILITIES,
	navigation,
	notifications,
	shareBaseUrl,
	onConfirmDelete,
}: AiReportsPageProps) {
	const nav = useMoatNavigation();
	const reportIdFromNav = nav.getSearchParam("reportId");

	if (reportIdFromNav) {
		return (
			<AiReportDetailPage
				capabilities={capabilities}
				navigation={navigation}
				notifications={notifications}
				reportId={reportIdFromNav}
				shareBaseUrl={shareBaseUrl}
			/>
		);
	}

	const resolvedCapabilities = capabilities ?? DEFAULT_CAPABILITIES;

	return (
		<AiReportsList
			capabilities={resolvedCapabilities}
			navigation={navigation}
			notifications={notifications}
			onConfirmDelete={onConfirmDelete}
			shareBaseUrl={shareBaseUrl}
		/>
	);
}

type AiReportsListProps = AiReportsPageProps & {
	capabilities: NonNullable<AiReportsPageProps["capabilities"]>;
};

function AiReportsList({
	capabilities,
	navigation,
	notifications,
	shareBaseUrl,
	onConfirmDelete,
}: AiReportsListProps) {
	const api = useApiClient();
	const queryClient = useQueryClient();

	const { data: reports = [], isLoading } = useQuery<AiReportSummary[]>({
		queryKey: ["aiReports"],
		queryFn: () => api.listReports(),
	});

	const shareMutation = useMutation({
		mutationFn: async ({ id, shared }: { id: string; shared: boolean }) => {
			if (shared) {
				return api.shareReport(id);
			}
			return api.unshareReport(id);
		},
		onSuccess: (_data, { shared }) => {
			void queryClient.invalidateQueries({ queryKey: ["aiReports"] });
			notifications?.success(
				shared ? "Report shared via link" : "Report set to private",
			);
		},
		onError: () => notifications?.error("Failed to update report visibility"),
	});

	const deleteMutation = useMutation({
		mutationFn: (id: string) => api.deleteReport(id),
		onSuccess: () => {
			void queryClient.invalidateQueries({ queryKey: ["aiReports"] });
			notifications?.success("Report deleted");
		},
		onError: () => notifications?.error("Failed to delete report"),
	});

	const confirmDelete =
		onConfirmDelete ??
		((message: string) =>
			typeof window !== "undefined" ? window.confirm(message) : false);

	return (
		<div className="flex flex-col gap-6">
			<div>
				<h2 className="font-bold text-2xl tracking-tight">
					AI-Generated Reports
				</h2>
				<p className="mt-1 text-muted-foreground text-sm">
					Financial reports generated by your AI assistant via the Moat MCP. Ask your
					agent to create a report and it will appear here automatically.
				</p>
			</div>

			{isLoading ? (
				<div className="grid grid-cols-1 gap-3 lg:grid-cols-2">
					{["s1", "s2", "s3", "s4", "s5", "s6"].map((k) => (
						<Skeleton className="h-28 rounded-xl" key={k} />
					))}
				</div>
			) : reports.length === 0 ? (
				<div className="flex flex-col items-center justify-center gap-3 rounded-xl border border-dashed p-16 text-center">
					<FlaskConical className="h-10 w-10 text-muted-foreground/50" />
					<div>
						<p className="font-medium text-sm">No reports yet</p>
						<p className="mt-1 text-muted-foreground text-sm">
							Ask your AI assistant to generate a financial report using the Moat MCP
							tools.
						</p>
					</div>
				</div>
			) : (
				<div className="grid grid-cols-1 gap-3 lg:grid-cols-2">
					{reports.map((report) => (
						<ReportCard
							capabilities={capabilities}
							key={report.id}
							onDelete={(id) => {
								if (confirmDelete("Delete this report? This cannot be undone.")) {
									deleteMutation.mutate(id);
								}
							}}
							onOpen={navigation.openReport}
							onShare={(id, shared) => shareMutation.mutate({ id, shared })}
							report={report}
							shareBaseUrl={shareBaseUrl}
						/>
					))}
				</div>
			)}
		</div>
	);
}
