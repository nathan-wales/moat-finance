import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CATEGORY_ICON_GROUPS, CATEGORY_ICONS } from "../src/category-icons.ts";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(
	scriptDir,
	"../../../apps/ios/Moat/Features/Categories/Models/category-icon-catalog.swift",
);

function swiftString(value: string): string {
	return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

const iconEntries = CATEGORY_ICONS.map(
	(icon) =>
		`        CategoryIconOption(key: ${swiftString(icon.key)}, label: ${swiftString(icon.label)}, group: ${swiftString(icon.group)}, systemImage: ${swiftString(icon.sfSymbol)})`,
).join(",\n");

const groupEntries = CATEGORY_ICON_GROUPS.map(
	(group) => `        ${swiftString(group)}`,
).join(",\n");

const contents = `// Generated by packages/contracts/scripts/generate-ios-category-icons.ts
// Do not edit by hand. Re-run: pnpm --filter @moat/contracts run gen:ios-category-icons

import Foundation

struct CategoryIconOption: Identifiable, Equatable, Hashable {
    let key: String
    let label: String
    let group: String
    let systemImage: String

    var id: String { key }
}

enum CategoryIconCatalog {
    static let groups: [String] = [
${groupEntries}
    ]

    static let all: [CategoryIconOption] = [
${iconEntries}
    ]

    static var grouped: [(group: String, icons: [CategoryIconOption])] {
        groups.compactMap { group in
            let icons = all.filter { $0.group == group }
            guard !icons.isEmpty else { return nil }
            return (group: group, icons: icons)
        }
    }

    static func systemImage(forKey key: String?) -> String? {
        guard let key else { return nil }
        return all.first(where: { $0.key == key })?.systemImage
    }

    static func option(forKey key: String?) -> CategoryIconOption? {
        guard let key else { return nil }
        return all.first(where: { $0.key == key })
    }
}
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, contents);
console.log(`Wrote ${CATEGORY_ICONS.length} icons to ${outputPath}`);
