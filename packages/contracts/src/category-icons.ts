export const CATEGORY_ICON_KEYS = new Set(
	CATEGORY_ICONS.map((icon) => icon.key),
);

export const categoryIconKeySchema = z
	.string()
	.refine((value) => CATEGORY_ICON_KEYS.has(value), {
		message: "Invalid category icon key",
	});

export function getCategoryIconDefinition(
	key: string | null | undefined,
): CategoryIconDefinition | undefined {
	if (!key) return undefined;
	return CATEGORY_ICONS.find((icon) => icon.key === key);
}

export function groupCategoryIcons(
	icons: readonly CategoryIconDefinition[] = CATEGORY_ICONS,
): Array<{ group: CategoryIconGroup; icons: CategoryIconDefinition[] }> {
	return CATEGORY_ICON_GROUPS.map((group) => ({
		group,
		icons: icons.filter((icon) => icon.group === group),
	})).filter((entry) => entry.icons.length > 0);
}
